// Garments AR: place a garment on the floor at true size with the 8th Wall engine (SLAM) + three.js.
// Flow: scan floor -> reticle appears on a detected surface -> tap (or "Place here") -> model stands there.
// One-finger drag rotates the model. No scaling: the model keeps its real-world size (absolute scale).

import * as THREE from 'three'
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js'
import {DRACOLoader} from 'three/addons/loaders/DRACOLoader.js'
import {RoomEnvironment} from 'three/addons/environments/RoomEnvironment.js'

window.THREE = THREE   // the 8th Wall three.js pipeline module expects the global

const DRACO_PATH = 'https://cdn.jsdelivr.net/npm/three@0.183.2/examples/jsm/libs/draco/gltf/'
const HIT_TYPES = ['DETECTED_SURFACE', 'ESTIMATED_SURFACE', 'FEATURE_POINT']
const CAMERA_HEIGHT = 1.4   // starting camera height above the world origin, metres

const ui = {
  hint: document.getElementById('hint'),
  controls: document.getElementById('controls'),
  place: document.getElementById('place'),
  reset: document.getElementById('reset'),
  title: document.getElementById('title'),
  back: document.getElementById('back'),
}
const setHint = (t) => { ui.hint.textContent = t; ui.hint.style.display = t ? '' : 'none' }

// ---- which garment? ../models.json is generated by build_site.py
const params = new URLSearchParams(location.search)
const modelId = params.get('m') || '1'
const manifest = await fetch('../models.json', {cache: 'no-cache'}).then(r => r.json()).catch(() => null)
const entry = manifest && manifest.models.find(m => String(m.id) === String(modelId))
if (!entry) {
  setHint('Unknown garment. Go back and scan the QR code again.')
  throw new Error('garment not found: ' + modelId)
}
ui.title.textContent = entry.name
ui.back.href = '../' + entry.id + '/'
document.title = entry.name + ' · AR'

// ---- scene content pipeline module
const scenePipelineModule = () => {
  let model = null          // loaded garment root (hidden until placed)
  let reticle = null        // ring shown on the detected floor
  let shadowPlane = null
  let placed = false
  let loadError = null
  let lastHit = null
  let dragStartX = null, dragStartRot = 0, dragging = false

  const loadModel = () => {
    const draco = new DRACOLoader().setDecoderPath(DRACO_PATH)
    const loader = new GLTFLoader().setDRACOLoader(draco)
    return new Promise((resolve, reject) => {
      loader.load('../' + entry.glb, (gltf) => {
        const root = gltf.scene
        root.traverse((o) => {
          if (o.isMesh) {
            o.castShadow = true
            o.frustumCulled = false
          }
        })
        resolve(root)
      }, undefined, reject)
    })
  }

  const initXrScene = ({scene, camera, renderer}) => {
    renderer.shadowMap.enabled = true
    renderer.shadowMap.type = THREE.PCFSoftShadowMap
    renderer.outputColorSpace = THREE.SRGBColorSpace
    renderer.toneMapping = THREE.ACESFilmicToneMapping
    renderer.toneMappingExposure = 1.0

    // image-based lighting so satin and skin read as PBR without downloading an HDR
    const pmrem = new THREE.PMREMGenerator(renderer)
    scene.environment = pmrem.fromScene(new RoomEnvironment(), 0.04).texture
    scene.environmentIntensity = 0.9

    const sun = new THREE.DirectionalLight(0xffffff, 1.6)
    sun.position.set(2, 5, 2)
    sun.castShadow = true
    sun.shadow.mapSize.set(1024, 1024)
    sun.shadow.camera.near = 0.1; sun.shadow.camera.far = 12
    sun.shadow.camera.left = sun.shadow.camera.bottom = -2
    sun.shadow.camera.right = sun.shadow.camera.top = 2
    sun.shadow.bias = -0.0005
    scene.add(sun)
    scene.add(new THREE.HemisphereLight(0xffffff, 0x666666, 0.6))

    // reticle
    reticle = new THREE.Mesh(
      new THREE.RingGeometry(0.16, 0.2, 48).rotateX(-Math.PI / 2),
      new THREE.MeshBasicMaterial({color: 0xff4d6d, transparent: true, opacity: 0.9, depthTest: false}))
    reticle.visible = false
    scene.add(reticle)

    // contact shadow under the model
    shadowPlane = new THREE.Mesh(
      new THREE.CircleGeometry(1.2, 48).rotateX(-Math.PI / 2),
      new THREE.ShadowMaterial({opacity: 0.45}))
    shadowPlane.receiveShadow = true
    shadowPlane.visible = false
    scene.add(shadowPlane)

    camera.position.set(0, CAMERA_HEIGHT, 0)

    loadModel().then((root) => {
      model = root
      model.visible = false
      scene.add(model)
      if (!placed) setHint('Move your phone slowly to scan the floor, then tap where the garment should stand.')
    }).catch((e) => {
      loadError = e
      setHint('Could not load the garment model. Check your connection and reload.')
      console.error(e)
    })
  }

  const place = (hit) => {
    if (!model || !hit) return
    const {camera} = XR8.Threejs.xrScene()
    model.position.set(hit.position.x, hit.position.y, hit.position.z)
    // face the viewer: rotate about Y so the garment's front (+Z) points at the camera
    const dx = camera.position.x - hit.position.x, dz = camera.position.z - hit.position.z
    model.rotation.set(0, Math.atan2(dx, dz), 0)
    model.visible = true
    shadowPlane.position.copy(model.position)
    shadowPlane.visible = true
    reticle.visible = false
    placed = true
    setHint('')
    ui.controls.classList.add('on')
    ui.place.style.display = 'none'
  }

  const reset = () => {
    placed = false
    if (model) model.visible = false
    shadowPlane.visible = false
    ui.place.style.display = ''
    setHint('Move your phone slowly to scan the floor, then tap where the garment should stand.')
  }

  // 8th Wall keeps the tracked floor at world y = 0, so a ray to that plane is a reliable fallback
  const raycaster = new THREE.Raycaster()
  const floorPlane = new THREE.Plane(new THREE.Vector3(0, 1, 0), 0)
  const floorHit = (nx, ny) => {
    const {camera} = XR8.Threejs.xrScene()
    raycaster.setFromCamera(new THREE.Vector2(nx * 2 - 1, -(ny * 2 - 1)), camera)
    const p = new THREE.Vector3()
    if (!raycaster.ray.intersectPlane(floorPlane, p)) return null
    const d = p.distanceTo(camera.position)
    if (d < 0.4 || d > 8) return null
    return {type: 'FLOOR_PLANE', position: {x: p.x, y: p.y, z: p.z}, distance: d}
  }

  const hitAt = (nx, ny) => {
    const hits = XR8.XrController.hitTest(nx, ny, HIT_TYPES) || []
    // prefer real surfaces, then estimated, then feature points, then the tracked floor plane
    for (const t of HIT_TYPES) { const h = hits.find(x => x.type === t); if (h) return h }
    return hits[0] || floorHit(nx, ny)
  }

  return {
    name: 'garments-scene',
    onStart: ({canvas}) => {
      const {scene, camera, renderer} = XR8.Threejs.xrScene()
      initXrScene({scene, camera, renderer})
      XR8.XrController.updateCameraProjectionMatrix({origin: camera.position, facing: camera.quaternion})

      canvas.addEventListener('touchmove', (e) => e.preventDefault(), {passive: false})

      // tap to place, drag to rotate
      canvas.addEventListener('touchstart', (e) => {
        if (e.touches.length !== 1) return
        dragging = false
        dragStartX = e.touches[0].clientX
        dragStartRot = model ? model.rotation.y : 0
      }, {passive: true})
      canvas.addEventListener('touchmove', (e) => {
        if (e.touches.length !== 1 || dragStartX === null || !placed || !model) return
        const dxp = e.touches[0].clientX - dragStartX
        if (Math.abs(dxp) > 6) dragging = true
        if (dragging) model.rotation.y = dragStartRot + dxp * 0.01
      }, {passive: true})
      canvas.addEventListener('touchend', (e) => {
        if (dragging || placed || e.changedTouches.length !== 1) { dragStartX = null; return }
        const t = e.changedTouches[0]
        const hit = hitAt(t.clientX / window.innerWidth, t.clientY / window.innerHeight) || lastHit
        if (hit) place(hit)
        else setHint('No floor found there yet. Point at the floor and move a little, then tap again.')
        dragStartX = null
      }, {passive: true})

      ui.place.addEventListener('click', () => { if (lastHit) place(lastHit) })
      ui.reset.addEventListener('click', reset)
      ui.controls.classList.add('on')
      setHint(model ? 'Tap where the garment should stand.' : 'Loading the garment…')
    },
    onUpdate: () => {
      if (placed || !reticle) return
      // keep the reticle on the floor at the screen centre so people see where the garment will land
      const hit = hitAt(0.5, 0.62)
      if (hit) {
        lastHit = hit
        reticle.position.set(hit.position.x, hit.position.y, hit.position.z)
        reticle.visible = !!model
        if (model && !loadError) setHint('Tap to place the garment on the floor.')
      } else {
        reticle.visible = false
        if (model && !loadError) setHint('Move your phone slowly to scan the floor.')
      }
    },
  }
}

const onxrloaded = () => {
  XR8.XrController.configure({scale: 'absolute', enableLighting: false})
  XR8.addCameraPipelineModules([
    XR8.GlTextureRenderer.pipelineModule(),      // camera feed
    XR8.Threejs.pipelineModule(),                // three.js scene
    XR8.XrController.pipelineModule(),           // SLAM world tracking
    LandingPage.pipelineModule(),                // unsupported device / desktop fallback page
    XRExtras.FullWindowCanvas.pipelineModule(),  // canvas fills the window
    XRExtras.Loading.pipelineModule(),           // loading screen + camera / motion permission prompts
    XRExtras.RuntimeError.pipelineModule(),      // error screen
    scenePipelineModule(),
  ])
  XR8.run({canvas: document.getElementById('camerafeed')})
}
window.XR8 ? onxrloaded() : window.addEventListener('xrloaded', onxrloaded)
